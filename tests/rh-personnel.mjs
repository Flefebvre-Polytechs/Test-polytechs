import assert from 'node:assert/strict';
import fs from 'node:fs';
const api=fs.readFileSync('app/api/habilitations/route.ts','utf8');
const directory=fs.readFileSync('app/rh/personnel/page.tsx','utf8');
const tree=fs.readFileSync('components/team-navigation.tsx','utf8');
const sidebar=fs.readFileSync('components/service-sidebar.tsx','utf8');
const habilitations=fs.readFileSync('app/habilitations/page.tsx','utf8');
assert.match(api,/const gate=await gateRead\(req\)/,'Directory must go through RH authorization gate');
assert.match(api,/scope'\)==='directory'/,'Directory has a dedicated API scope');
const personQuery=api.match(/db\.prepare\('SELECT ([^']+) FROM hr_people ORDER BY last_name,first_name'\)\.all\(\)/);
assert.ok(personQuery,'Directory must use a minimal SELECT projection');
assert.doesNotMatch(personQuery[1],/\*|qr_token|password|email|medical/,'Do not reveal QR tokens or health fields in directory');
assert.match(directory,/\/api\/habilitations\?scope=directory/);
assert.match(directory,/action:'create-person'/);
assert.match(directory,/action:'update-person'/);
assert.match(directory,/action:'deactivate-person'/);
assert.match(directory,/confirmation:'SUPPRIMER'/);
assert.match(directory,/href=\{'\/habilitations\?person='/,'Personnel links to the existing authorization register');
assert.match(habilitations,/get\('person'\)/,'Habilitations must honor employee deep links');
assert.match(tree,/href="\/rh\/personnel"/,'RH menu exposes personnel register');
assert.match(sidebar,/href="\/rh\/personnel"/,'Staff directory is accessible from the main sidebar');
console.log('Personnel directory: RH gate, minimized data, shared employee records, deep links and audit-safe deactivation passed.');
